import React, { useState } from 'react';
import { Copy, Check, ShieldCheck, KeyRound, UserCheck } from 'lucide-react';
import { Modal } from './Modal';
import { StudentCredentials } from '../../types';

interface CredentialModalProps {
  isOpen: boolean;
  onClose: () => void;
  credentials: StudentCredentials | null;
  studentName: string;
}

export const CredentialModal: React.FC<CredentialModalProps> = ({
  isOpen,
  onClose,
  credentials,
  studentName,
}) => {
  const [copiedId, setCopiedId] = useState(false);
  const [copiedPass, setCopiedPass] = useState(false);

  if (!credentials) return null;

  const copyToClipboard = async (text: string, type: 'id' | 'pass') => {
    try {
      await navigator.clipboard.writeText(text);
      if (type === 'id') {
        setCopiedId(true);
        setTimeout(() => setCopiedId(false), 2000);
      } else {
        setCopiedPass(true);
        setTimeout(() => setCopiedPass(false), 2000);
      }
    } catch {
      // Fallback
    }
  };

  return (
    <Modal
      isOpen={isOpen}
      onClose={onClose}
      title="Student Credentials Generated"
      subtitle={`Account created successfully for ${studentName}`}
      maxWidth="md"
    >
      <div className="space-y-4">
        {/* Notice alert */}
        <div className="flex items-start gap-3 p-3.5 rounded-lg bg-amber-50/70 border border-amber-200/80 text-amber-900">
          <ShieldCheck className="w-5 h-5 text-amber-700 shrink-0 mt-0.5" />
          <div className="text-xs space-y-1">
            <p className="font-semibold text-amber-950">Confidential One-Time Credentials</p>
            <p className="text-amber-800 leading-relaxed">
              These initial credentials have been generated by the server. Share them directly with the student via official secure SMS or academic portal memo. The password will not be stored in plaintext.
            </p>
          </div>
        </div>

        {/* Credentials box */}
        <div className="p-4 bg-slate-50 rounded-xl border border-slate-200/90 space-y-3.5">
          {/* Student ID */}
          <div>
            <label className="block text-xs font-semibold text-slate-500 uppercase tracking-wider mb-1.5 flex items-center gap-1.5">
              <UserCheck className="w-3.5 h-3.5 text-slate-600" />
              Assigned Student ID
            </label>
            <div className="flex items-center justify-between p-2.5 bg-white rounded-lg border border-slate-200 font-mono text-sm font-semibold text-slate-900">
              <span className="tabular-nums tracking-wide">{credentials.student_id}</span>
              <button
                type="button"
                onClick={() => copyToClipboard(credentials.student_id, 'id')}
                className="inline-flex items-center gap-1 text-xs font-medium text-slate-600 hover:text-slate-900 p-1 px-2 rounded bg-slate-100 hover:bg-slate-200 transition-colors"
                title="Copy Student ID"
              >
                {copiedId ? (
                  <>
                    <Check className="w-3.5 h-3.5 text-emerald-600" />
                    <span className="text-emerald-700">Copied</span>
                  </>
                ) : (
                  <>
                    <Copy className="w-3.5 h-3.5 text-slate-500" />
                    <span>Copy ID</span>
                  </>
                )}
              </button>
            </div>
          </div>

          {/* Initial Password */}
          <div>
            <label className="block text-xs font-semibold text-slate-500 uppercase tracking-wider mb-1.5 flex items-center gap-1.5">
              <KeyRound className="w-3.5 h-3.5 text-slate-600" />
              Temporary Initial Password
            </label>
            <div className="flex items-center justify-between p-2.5 bg-white rounded-lg border border-slate-200 font-mono text-sm font-semibold text-slate-900">
              <span className="tabular-nums tracking-wide text-indigo-700">{credentials.initial_password}</span>
              <button
                type="button"
                onClick={() => copyToClipboard(credentials.initial_password, 'pass')}
                className="inline-flex items-center gap-1 text-xs font-medium text-slate-600 hover:text-slate-900 p-1 px-2 rounded bg-slate-100 hover:bg-slate-200 transition-colors"
                title="Copy Password"
              >
                {copiedPass ? (
                  <>
                    <Check className="w-3.5 h-3.5 text-emerald-600" />
                    <span className="text-emerald-700">Copied</span>
                  </>
                ) : (
                  <>
                    <Copy className="w-3.5 h-3.5 text-slate-500" />
                    <span>Copy Password</span>
                  </>
                )}
              </button>
            </div>
          </div>
        </div>

        {/* Action button */}
        <div className="flex justify-end pt-2">
          <button
            type="button"
            onClick={onClose}
            className="px-5 py-2 text-xs font-semibold text-white bg-slate-900 hover:bg-slate-800 rounded-lg transition-colors"
          >
            I Have Saved These Credentials
          </button>
        </div>
      </div>
    </Modal>
  );
};
